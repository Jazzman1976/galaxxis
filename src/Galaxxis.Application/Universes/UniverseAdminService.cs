using Galaxxis.Domain.Planets;
using Galaxxis.Domain.Universes.Generation;
using Galaxxis.Persistence.Game;
using Galaxxis.Persistence.Game.Entities;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace Galaxxis.Application.Universes;

/// <summary>
/// Implementation of <see cref="IUniverseAdminService"/>: turns a generated blueprint into database rows
/// and manages the pause state of universes.
/// </summary>
internal sealed class UniverseAdminService(
    GameDbContext context,
    TimeProvider timeProvider,
    IOptions<UniverseGenerationOptions> options,
    ILogger<UniverseAdminService> logger) : IUniverseAdminService
{
    /// <inheritdoc />
    public async Task<UniverseSummary> GenerateAsync(GenerateUniverseRequest request, CancellationToken cancellationToken = default)
    {
        int seed = request.Seed ?? Random.Shared.Next();
        TimeSpan tickLength = request.TickLength ?? options.Value.TickLength;
        ValidateTickLength(tickLength);

        // The map itself is generated by pure Domain code; this service only stores it.
        UniverseBlueprint blueprint = UniverseGenerator.Generate(request.Map, seed);
        DateTimeOffset now = timeProvider.GetUtcNow();

        Universe universe = new()
        {
            Name = blueprint.Name,
            GenerationSeed = seed,
            CreatedAt = now,
            TickLength = tickLength,

            // Tick 0 starts now, but the universe starts paused: while paused, time does not advance, so it
            // is still at tick 0 whenever an administrator resumes it.
            Epoch = now,
            PausedSince = now,
            TotalPausedDuration = TimeSpan.Zero,
        };

        universe.Galaxies = blueprint.Galaxies.Select(galaxy => new Galaxy
        {
            Name = galaxy.Name,
            Coordinate = galaxy.Coordinate,
            StarSystems = galaxy.StarSystems.Select(system => new StarSystem
            {
                Name = system.Name,
                Coordinate = system.Coordinate,
                Planets = system.Planets.Select(planet => CreatePlanet(universe, planet)).ToList(),
            }).ToList(),
        }).ToList();

        // One SaveChanges call runs in one database transaction: the universe is stored completely or not at all.
        context.Universes.Add(universe);
        await context.SaveChangesAsync(cancellationToken);

        logger.LogInformation(
            "Generated universe {UniverseId} \"{Name}\" with {PlanetCount} planets (seed {Seed}). It is paused until resumed.",
            universe.Id, universe.Name, blueprint.PlanetCount, seed);

        return await SummaryAsync(universe.Id, cancellationToken)
            ?? throw new InvalidOperationException($"Universe {universe.Id} disappeared right after it was created.");
    }

    /// <inheritdoc />
    public async Task<IReadOnlyList<UniverseSummary>> ListAsync(CancellationToken cancellationToken = default) =>
        await Summaries(context.Universes.OrderBy(universe => universe.Id)).ToListAsync(cancellationToken);

    /// <inheritdoc />
    public async Task<UniverseSummary?> ResumeAsync(int universeId, CancellationToken cancellationToken = default)
    {
        Universe? universe = await context.Universes.SingleOrDefaultAsync(u => u.Id == universeId, cancellationToken);
        if (universe is null)
        {
            return null;
        }

        if (universe.PausedSince is DateTimeOffset pausedSince)
        {
            // Add the pause to the total, so universe time continues exactly where it stopped.
            universe.TotalPausedDuration += timeProvider.GetUtcNow() - pausedSince;
            universe.PausedSince = null;
            await context.SaveChangesAsync(cancellationToken);

            logger.LogInformation("Resumed universe {UniverseId} \"{Name}\".", universe.Id, universe.Name);
        }

        return await SummaryAsync(universeId, cancellationToken);
    }

    /// <inheritdoc />
    public async Task<UniverseSummary?> PauseAsync(int universeId, CancellationToken cancellationToken = default)
    {
        Universe? universe = await context.Universes.SingleOrDefaultAsync(u => u.Id == universeId, cancellationToken);
        if (universe is null)
        {
            return null;
        }

        if (universe.PausedSince is null)
        {
            universe.PausedSince = timeProvider.GetUtcNow();
            await context.SaveChangesAsync(cancellationToken);

            logger.LogInformation("Paused universe {UniverseId} \"{Name}\".", universe.Id, universe.Name);
        }

        return await SummaryAsync(universeId, cancellationToken);
    }

    private static Planet CreatePlanet(Universe universe, PlanetBlueprint blueprint) => new()
    {
        Universe = universe,
        Name = blueprint.Name,
        Coordinate = blueprint.Coordinate,
        Fields = blueprint.Fields,

        // Unclaimed until a player receives it as starting planet.
        OwnerPlayerId = null,
        Stock = PlanetDefaults.StartingStock,
        Buildings = PlanetDefaults.Buildings,
        ResourcesSettledTick = 0,

        Moons = blueprint.Moons.Select(moon => new Moon { Name = moon.Name, Fields = moon.Fields }).ToList(),
    };

    private static void ValidateTickLength(TimeSpan tickLength)
    {
        if (tickLength < UniverseGenerationOptions.MinimumTickLength || tickLength > UniverseGenerationOptions.MaximumTickLength)
        {
            throw new ArgumentOutOfRangeException(
                nameof(tickLength), tickLength, "The tick length must be between 100 milliseconds and 1 day.");
        }
    }

    private Task<UniverseSummary?> SummaryAsync(int universeId, CancellationToken cancellationToken) =>
        Summaries(context.Universes.Where(universe => universe.Id == universeId)).SingleOrDefaultAsync(cancellationToken);

    /// <summary>
    /// Projects universes to summaries. Filter and sort <paramref name="universes"/> <b>before</b> calling this:
    /// EF Core cannot translate a filter on the projected record into SQL.
    /// </summary>
    private IQueryable<UniverseSummary> Summaries(IQueryable<Universe> universes) =>
        universes.AsNoTracking().Select(universe => new UniverseSummary(
            universe.Id,
            universe.Name,
            universe.GenerationSeed,
            universe.TickLength,
            universe.PausedSince != null,
            universe.Galaxies.Count,
            context.Planets.Count(planet => planet.UniverseId == universe.Id),
            context.Planets.Count(planet => planet.UniverseId == universe.Id && planet.OwnerPlayerId != null),
            universe.CreatedAt));
}
