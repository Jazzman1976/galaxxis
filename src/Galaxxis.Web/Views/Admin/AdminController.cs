using Galaxxis.Application.Universes;
using Galaxxis.Persistence.Accounts;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Extensions.Options;

namespace Galaxxis.Web.Views.Admin;

/// <summary>
/// Administration: the universes with their state; generate new ones, pause and resume them.
/// </summary>
/// <remarks>
/// Only accounts with the <see cref="AccountRoles.Admin"/> role get here; the first admin is created with
/// <c>UniverseGenerator -- bootstrap-admin</c> (deliberately not on a web page, see the audit). Everything else the
/// generator tool does is available here as well. Universes keep running on their own; pausing is meant for
/// maintenance.
/// </remarks>
[Authorize(Roles = AccountRoles.Admin)]
public sealed class AdminController(
    IUniverseAdminService universes,
    IOptions<UniverseGenerationOptions> generationDefaults,
    ILogger<AdminController> logger) : Controller
{
    /// <summary>Key of the confirmation shown once after an action (kept in TempData across the redirect).</summary>
    public const string MessageKey = "AdminMessage";

    /// <summary>Shows all universes and the form for generating a new one.</summary>
    /// <param name="cancellationToken">Aborted when the request is aborted.</param>
    /// <returns>The admin page.</returns>
    [HttpGet]
    public async Task<IActionResult> Index(CancellationToken cancellationToken) =>
        await AdminPageAsync(GenerateUniverseViewModel.FromDefaults(generationDefaults.Value), cancellationToken);

    /// <summary>
    /// Generates a universe with the values of the form. It starts paused unless "start immediately" is checked.
    /// </summary>
    /// <param name="form">The form values.</param>
    /// <param name="cancellationToken">Aborted when the request is aborted.</param>
    /// <returns>A redirect back to the admin page, or the page with the reasons if the values are refused.</returns>
    [HttpPost]
    public async Task<IActionResult> Generate([Bind(Prefix = nameof(AdminViewModel.Generate))] GenerateUniverseViewModel form, CancellationToken cancellationToken)
    {
        if (!ModelState.IsValid)
        {
            return await AdminPageAsync(form, cancellationToken);
        }

        UniverseSummary universe;
        try
        {
            universe = await universes.GenerateAsync(form.ToRequest(generationDefaults.Value), cancellationToken);
        }
        catch (Exception exception) when (exception is ArgumentException or InvalidOperationException)
        {
            // The map settings do not fit together (for example too many planets for the coordinate range). The message
            // comes from the Domain and is English, which is acceptable on the admin page.
            ModelState.AddModelError(string.Empty, $"Das Universum konnte nicht erzeugt werden: {exception.Message}");
            return await AdminPageAsync(form, cancellationToken);
        }

        logger.LogWarning("Universe {UniverseId} generated by {Admin}.", universe.Id, User.Identity?.Name);

        if (form.StartImmediately)
        {
            universe = await universes.ResumeAsync(universe.Id, cancellationToken) ?? universe;
            logger.LogWarning("Universe {UniverseId} resumed by {Admin}.", universe.Id, User.Identity?.Name);
        }

        TempData[MessageKey] = $"Universum #{universe.Id} „{universe.Name}“ mit {universe.PlanetCount:N0} Planeten erzeugt. " +
            (universe.IsPaused ? "Es ist pausiert; mit „Starten“ können Spieler loslegen." : "Es läuft bereits.");
        return RedirectToAction(nameof(Index));
    }

    /// <summary>Pauses a universe: its time stands still, nothing is produced and no order progresses.</summary>
    /// <param name="id">The universe.</param>
    /// <param name="cancellationToken">Aborted when the request is aborted.</param>
    /// <returns>A redirect back to the admin page, or 404.</returns>
    [HttpPost]
    public async Task<IActionResult> Pause(int id, CancellationToken cancellationToken)
    {
        UniverseSummary? universe = await universes.PauseAsync(id, cancellationToken);
        if (universe is null)
        {
            return NotFound();
        }

        logger.LogWarning("Universe {UniverseId} paused by {Admin}.", id, User.Identity?.Name);
        TempData[MessageKey] = $"Universum #{universe.Id} „{universe.Name}“ ist pausiert.";
        return RedirectToAction(nameof(Index));
    }

    /// <summary>Resumes a paused universe; the paused time is not counted as game time.</summary>
    /// <param name="id">The universe.</param>
    /// <param name="cancellationToken">Aborted when the request is aborted.</param>
    /// <returns>A redirect back to the admin page, or 404.</returns>
    [HttpPost]
    public async Task<IActionResult> Resume(int id, CancellationToken cancellationToken)
    {
        UniverseSummary? universe = await universes.ResumeAsync(id, cancellationToken);
        if (universe is null)
        {
            return NotFound();
        }

        logger.LogWarning("Universe {UniverseId} resumed by {Admin}.", id, User.Identity?.Name);
        TempData[MessageKey] = $"Universum #{universe.Id} „{universe.Name}“ läuft.";
        return RedirectToAction(nameof(Index));
    }

    private async Task<IActionResult> AdminPageAsync(GenerateUniverseViewModel form, CancellationToken cancellationToken) =>
        View("Admin", new AdminViewModel(await universes.ListAsync(cancellationToken), form));
}
